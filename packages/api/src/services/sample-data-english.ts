const YEARS_AGO = /^(.*) \(il y a (\d+) ans\)$/;

export function englishName(name: string): string {
	const aged = YEARS_AGO.exec(name);

	if (aged?.[1] !== undefined) {
		return `${englishName(aged[1])} (${aged[2]} years ago)`;
	}

	return ENGLISH.get(name) ?? name;
}

/** The sample household with every name Archant wrote in English. */
export function englishSample(sample: SamplePlan): SamplePlan {
	const { plan } = sample;

	return {
		plan: {
			...plan,
			accounts: plan.accounts.map((account) => ({ ...account, name: englishName(account.name) })),
			categories: plan.categories.map((category) => ({
				...category,
				name: englishName(category.name),
			})),
			transactions: plan.transactions.map((row) => ({ ...row, label: englishName(row.label) })),
		},
		goals: sample.goals.map((goal) => ({ ...goal, name: englishName(goal.name) })),
	};
}
