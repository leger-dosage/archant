export type HouseholdCountry = keyof typeof COUNTRY_CURRENCIES;

export function isHouseholdCountry(value: string): value is HouseholdCountry {
	return Object.hasOwn(COUNTRY_CURRENCIES, value);
}

export const HOUSEHOLD_COUNTRIES = Object.keys(COUNTRY_CURRENCIES).filter(isHouseholdCountry);
export const DEFAULT_HOUSEHOLD_COUNTRY: HouseholdCountry = "FR";

export function currencyForCountry(country: HouseholdCountry): CurrencyCode {
	const currency = COUNTRY_CURRENCIES[country];

	return isCurrencyCode(currency) ? currency : "USD";
}

// Sure's Family::DATE_FORMATS. The tokens double as the labels in the form.
export const DATE_FORMATS = [
	"MM-DD-YYYY",
	"DD.MM.YYYY",
	"DD-MM-YYYY",
	"YYYY-MM-DD",
	"DD/MM/YYYY",
	"YYYY/MM/DD",
	"MM/DD/YYYY",
	"D/MM/YYYY",
	"YYYY.MM.DD",
	"YYYYMMDD",
	"DD MMM YYYY",
] as const;

export type HouseholdDateFormat = (typeof DATE_FORMATS)[number];

export function defaultDateFormat(locale: Locale): HouseholdDateFormat {
	return locale === "fr" ? "DD/MM/YYYY" : "MM/DD/YYYY";
}

export const DEFAULT_TIME_ZONE = "Europe/Paris";

export function isTimeZone(value: string): boolean {
	try {
		return new Intl.DateTimeFormat("en", { timeZone: value }).resolvedOptions().timeZone !== "";
	} catch {
		return false;
	}
}
